"""A kind's generated `index.md`: a table of its non-terminal items."""

from itemctl.model import Kind, Snapshot, text_of
from itemctl.schema import id_number, is_terminal


def index_text(snap: Snapshot, kind: Kind) -> str:
    """The markdown table of the kind's `index` columns over its non-terminal items, by id."""
    items = sorted(
        (i for i in snap.items if i.kind == kind.name and not is_terminal(snap.schema, i)),
        key=lambda i: id_number(snap.schema, i.id) or 0,
    )
    rows = [
        "| "
        + " | ".join(text_of(i.fields.get(c, "")).replace("|", "\\|") for c in kind.index)
        + " |"
        for i in items
    ]
    head = ["| " + " | ".join(kind.index) + " |", "|" + "---|" * len(kind.index)]
    intro = f"# {kind.name}\n\nGenerated by itemctl on every write; do not edit.\n\n"
    return intro + "\n".join(head + rows) + "\n"
